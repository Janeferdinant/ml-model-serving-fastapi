"""Bundle the explorer's precomputed data into docs/data.js (opened from file://, no server).

Inputs: the app's OpenAPI document, the committed load-test and latency run files, the drift
demo and the production model's metadata. Run after ``loadtest/run_loadtest.py`` and
``scripts/make_drift_demo.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from mlserving import registry
from mlserving.app import create_app
from mlserving.config import Settings

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def newest(pattern: str) -> Path:
    files = sorted((DOCS / "runs").glob(pattern))
    if not files:
        raise SystemExit(f"no files match docs/runs/{pattern}")
    return files[-1]


def model_card() -> dict[str, Any]:
    model_dir = ROOT / "models"
    reg = registry.load_registry(model_dir)
    version = registry.resolve_version(model_dir, "production")
    meta = registry.verify_version(model_dir, version)
    keep = (
        "version",
        "model_type",
        "target",
        "hyperparameters",
        "seed",
        "metrics",
        "dataset",
        "git",
        "trained_at",
        "library_versions",
        "feature_schema",
    )
    card = {k: meta[k] for k in keep}
    card["model_sha256"] = meta["artifacts"]["model"]["sha256"]
    card["versions"] = [
        {"version": v.version, "stage": v.stage, "created_at": v.created_at}
        for v in registry.list_versions(model_dir)
    ]
    card["history"] = reg["history"]
    return card


def main() -> int:
    app = create_app(Settings(model_dir=ROOT / "models", strict_startup=False))
    data = {
        "openapi": app.openapi(),
        "model": model_card(),
        "loadtest": json.loads(newest("*-loadtest.json").read_text(encoding="utf-8")),
        "latency": json.loads(newest("*-predict-latency.json").read_text(encoding="utf-8")),
        "drift": json.loads((DOCS / "data" / "drift_demo.json").read_text(encoding="utf-8")),
    }
    out = DOCS / "data.js"
    out.write_text(
        "// Generated by scripts/build_explorer.py. Do not edit.\n"
        "window.EXPLORER_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out} ({out.stat().st_size / 1024:.0f} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
